"""PCM16 WAV writer (RIFF/WAVE with `fmt ` and `data`), stdlib only.

The bytes are generated by hand instead of using `wave` so they can be written with
`ngb_tools._paths.atomic_write_chunks` (`.part` and rename); `wave` reads them back fine.
"""

from __future__ import annotations

import struct
from array import array
from collections.abc import Iterator
from typing import Final

from ngb_tools.audio.pcm import to_le_bytes

PCM_TAG: Final = 1
BITS: Final = 16
_FMT: Final = struct.Struct("<4sI4s4sIHHIIHH4sI")
_MAX_RIFF: Final = 0xFFFFFFFF


def wav_header(channels: int, sample_rate: int, frames: int) -> bytes:
    """44-byte header for `frames` PCM16 samples per channel."""
    block = channels * BITS // 8
    data_size = frames * block
    if data_size + _FMT.size - 8 > _MAX_RIFF:
        raise ValueError(f"{data_size} bytes of audio do not fit in a RIFF")
    return _FMT.pack(
        b"RIFF",
        data_size + _FMT.size - 8,
        b"WAVE",
        b"fmt ",
        16,
        PCM_TAG,
        channels,
        sample_rate,
        sample_rate * block,
        block,
        BITS,
        b"data",
        data_size,
    )


def iter_wav_chunks(samples: array[int], channels: int, sample_rate: int) -> Iterator[bytes]:
    """Header and data of a WAV with `samples` (interleaved PCM16)."""
    if channels <= 0 or len(samples) % channels:
        raise ValueError(f"{len(samples)} samples do not split into {channels} channels")
    yield wav_header(channels, sample_rate, len(samples) // channels)
    yield to_le_bytes(samples)


def wav_bytes(samples: array[int], channels: int, sample_rate: int) -> bytes:
    return b"".join(iter_wav_chunks(samples, channels, sample_rate))
