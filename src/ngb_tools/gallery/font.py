def glyph(char: str) -> tuple[int, ...]:
    return GLYPHS.get(char.upper(), GLYPHS["?"])


def text_width(text: str, scale: int = 1) -> int:
    return max(0, len(text) * ADVANCE * scale - scale)


def draw_text(
    rgb: bytearray,
    width: int,
    x: int,
    y: int,
    text: str,
    *,
    color: tuple[int, int, int],
    scale: int = 1,
) -> None:
    """Pinta `text` en un búfer RGB de `width` de ancho; lo que se sale se recorta."""
    height = len(rgb) // (3 * width)
    paint = bytes(color)
    for k, char in enumerate(text):
        rows = glyph(char)
        for row, bits in enumerate(rows):
            for col in range(GLYPH_WIDTH):
                if not bits & (1 << (GLYPH_WIDTH - 1 - col)):
                    continue
                for dy in range(scale):
                    for dx in range(scale):
                        px = x + (k * ADVANCE + col) * scale + dx
                        py = y + row * scale + dy
                        if 0 <= px < width and 0 <= py < height:
                            i = 3 * (py * width + px)
                            rgb[i : i + 3] = paint
