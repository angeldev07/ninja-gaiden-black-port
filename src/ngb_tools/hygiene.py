"""Repo hygiene guard: keeps game data from being versioned.

ALWAYS reads from the git index, never from the working tree: what is judged is the blob
that would enter the commit. That leaves no bypass (staging a game blob and then
overwriting the file on disk) and no failures from deleted files or dangling symlinks.
Gitlinks (submodules) are skipped; a symlink is a blob holding the target path and is
evaluated like any other. git runs without replace objects (a `refs/replace/*` cannot
disguise a blob), without lazy fetches (a missing object is an error, not a network wait)
and with a per-call time limit.

Each blob goes through four independent barriers:

1. Path under `game/`, `extracted/` or `build/` at the root: the same as .gitignore
   ignores, but also when forced with `git add -f`.
2. Forbidden extension (game formats and compressed archives). The name is folded before
   comparing (NFKD without diacritics and A-Z -> a-z), so `CMN.İSO` or `x.ＩＳＯ` do not
   escape.
3. Binary signature at the start of the blob (or the XDVDFS magic at 0x10000), which
   catches renames.
4. Size above the limit (a dump or an asset that slipped in).

The signatures are heuristics: they cover the formats verified on the disc, not every
possible one. That is why extension and size remain barriers of their own.

`.ttf` fonts are not blocked by extension: a free font may be legitimate. The game's own
(23 MB) are caught by size. .gitignore does ignore `*.ttf`, so a free font goes in with
`git add -f`.

Exceptions: `.hygiene-allow` at the root (64 KiB maximum), one exact path per line and `#`
for comments. An allowed path skips ONLY the extension rule. With `--staged` the list from
HEAD, already committed, applies so that a commit cannot exempt itself: the exception goes
in earlier and in plain sight. In CI the index list applies, which is the PR's tree and goes
through review. Without HEAD (freshly created repo), the list is empty.

Known limit: the tree (the index) is checked, not the history. That is enough because PRs
are squash-merged: only the PR's final tree reaches `main`, and CI checks it in full.

TODO(performance): one `git cat-file blob` process per blob (~20 ms on Windows, ~0.3 s in
total today). If the repo grows to thousands of files, switch to a single `cat-file --batch`.

Usage:
    python -m ngb_tools.hygiene            # the whole index (CI)
    python -m ngb_tools.hygiene --staged   # only what is staged (pre-commit hook)

Exit codes: 0 clean, 1 violations found, 2 git or configuration error.
"""

from __future__ import annotations

import argparse
import contextlib
import os
import shlex
import signal
import string
import subprocess
import sys
import threading
import unicodedata
from collections.abc import Callable, Iterable, Mapping, Sequence
from dataclasses import dataclass
from enum import StrEnum
from functools import partial
from pathlib import Path, PurePosixPath
from typing import Final

# --- Rules -----------------------------------------------------------------------------

_GAME_DATA: Final = "game data"
_ARCHIVE: Final = "compressed archive (could contain game data)"

# Forbidden extensions, grouped by origin. A new entry here requires updating
# docs/target/adr-03-game-data-outside-repo.md.
_DISC_FILES = (".xbe", ".iso", ".xiso", ".bin", ".def", ".ins")
_CRI_MIDDLEWARE = (".afs", ".sfd", ".aix", ".adx")
_XDK_RESOURCES = (".xpr", ".xwb", ".xsb")
_AFS_PAYLOADS = (".kmd", ".spr", ".sty", ".wva", ".mtn", ".rtm", ".sob", ".itm", ".chr", ".stg")
_ARCHIVES = (".zip", ".7z", ".rar", ".tar", ".gz", ".tgz", ".bz2", ".xz", ".zst")
FORBIDDEN_EXTENSIONS: Final[Mapping[str, str]] = {
    **dict.fromkeys((*_DISC_FILES, *_CRI_MIDDLEWARE, *_XDK_RESOURCES, *_AFS_PAYLOADS), _GAME_DATA),
    **dict.fromkeys(_ARCHIVES, _ARCHIVE),
}

# Top-level directories that .gitignore ignores; here they also count with `add -f`.
FORBIDDEN_ROOTS: Final[Mapping[str, str]] = {
    "game": "copy of the game",
    "extracted": "data extracted from the game",
    "build": "output generated by the tools",
}

_ASCII_LOWER: Final = str.maketrans(string.ascii_uppercase, string.ascii_lowercase)

# Exact-prefix signatures, verified on the game files or standard for the format.
_PREFIX_SIGNATURES: Final[tuple[tuple[bytes, str], ...]] = (
    (b"XBEH", "XBE executable"),
    (b"AFS\x00", "CRI AFS container"),
    (b"XPR0", "Xbox Packed Resource"),
    (b"KMD\x00", "Team Ninja KMD model"),
    (b"WBND", "XACT wave bank (.xwb)"),
    (b"SDBK", "XACT sound bank (.xsb)"),
    (b"AIXF", "CRI AIX audio"),
    (b"\x00\x00\x01\xba", "MPEG Program Stream (Sofdec .sfd video)"),
    (b"PK\x03\x04", _ARCHIVE),  # zip
    (b"7z\xbc\xaf\x27\x1c", _ARCHIVE),
    (b"Rar!\x1a\x07", _ARCHIVE),  # RAR 4 and 5
    (b"\x1f\x8b", _ARCHIVE),  # gzip
    (b"\xfd7zXZ\x00", _ARCHIVE),  # xz
    (b"\x28\xb5\x2f\xfd", _ARCHIVE),  # zstd
)

HEAD_BYTES: Final = 0x20

# CRI ADX: `80 00` and, in bytes 2-3 (big endian), the offset of the `(c)CRI` copyright.
_ADX_MAGIC: Final = b"\x80\x00"
_ADX_COPYRIGHT_OFFSETS: Final = range(0x10, 0x200 + 1)

# Team Ninja chunk header (KMD, itm_dat2, chr_dat, stry_dat, rtm_dat... inside the AFS
# files): 12-byte NUL-padded ASCII tag at 0x00 (>= 3 printable), u32 LE at 0x18 in
# {0x20, 0x40, 0x80} and u32 LE at 0x1C = 0x20. Observed values, not specified.
_TN_TAG_SIZE: Final = 12
_TN_MIN_TAG_CHARS: Final = 3
_TN_FIELD_18_VALUES: Final = frozenset({0x20, 0x40, 0x80})
_TN_FIELD_1C_VALUE: Final = 0x20

# bzip2: `BZh`, level 1-9 and the first block magic (or the end-of-stream one if empty).
_BZIP2_BLOCK_MAGICS: Final = (b"\x31\x41\x59\x26\x53\x59", b"\x17\x72\x45\x38\x50\x90")

# XISO image: XDVDFS magic at sector 32.
XDVDFS_MAGIC: Final = b"MICROSOFT*XBOX*MEDIA"
XDVDFS_OFFSET: Final = 0x10000
_XDVDFS_END: Final = XDVDFS_OFFSET + len(XDVDFS_MAGIC)

DEFAULT_MAX_BYTES: Final = 1024 * 1024


class Rule(StrEnum):
    """Rule that a path has violated."""

    PATH = "path"
    EXTENSION = "extension"
    SIGNATURE = "signature"
    SIZE = "size"


@dataclass(frozen=True, slots=True)
class Violation:
    """A path that must not enter the repo, and why."""

    path: str
    rule: Rule
    detail: str

    def __str__(self) -> str:
        return f"{self.path}: [{self.rule}] {self.detail}"


@dataclass(frozen=True, slots=True)
class Policy:
    """Review parameters: size limit and paths exempt from the extension rule."""

    max_bytes: int = DEFAULT_MAX_BYTES
    allowed: frozenset[str] = frozenset()


DEFAULT_POLICY: Final = Policy()


def _fold(text: str) -> str:
    """Fold a name for comparison: NFKD without combining marks, then A-Z -> a-z.

    `str.lower` is not enough: 'İ'.lower() is 'i' + U+0307, and `CMN.İSO` would not end in
    `.iso`. NFKD also reduces full-width forms ('ＩＳＯ') and the Kelvin sign to ASCII.
    """
    decomposed = unicodedata.normalize("NFKD", text)
    bare = "".join(char for char in decomposed if not unicodedata.combining(char))
    return bare.translate(_ASCII_LOWER)


def forbidden_extension(path: str) -> str | None:
    """Forbidden extension that the name of `path` ends in, if any (`.iso` included)."""
    name = _fold(PurePosixPath(path).name)
    return next((ext for ext in FORBIDDEN_EXTENSIONS if name.endswith(ext)), None)


def forbidden_root(path: str) -> str | None:
    """Forbidden top-level directory that contains `path`, if any (folded)."""
    parts = PurePosixPath(path).parts
    if len(parts) < 2:
        return None
    root = _fold(parts[0])
    return root if root in FORBIDDEN_ROOTS else None


def _match_prefix(head: bytes) -> str | None:
    return next((desc for magic, desc in _PREFIX_SIGNATURES if head.startswith(magic)), None)


def _match_adx(head: bytes) -> str | None:
    if len(head) < 4 or not head.startswith(_ADX_MAGIC):
        return None
    copyright_offset = int.from_bytes(head[2:4], "big")
    return "CRI ADX audio" if copyright_offset in _ADX_COPYRIGHT_OFFSETS else None


def _match_team_ninja_chunk(head: bytes) -> str | None:
    if len(head) < HEAD_BYTES:
        return None
    tag = head[:_TN_TAG_SIZE].rstrip(b"\0")
    if len(tag) < _TN_MIN_TAG_CHARS or not all(0x20 <= byte <= 0x7E for byte in tag):
        return None
    field_18 = int.from_bytes(head[0x18:0x1C], "little")
    field_1c = int.from_bytes(head[0x1C:0x20], "little")
    if field_18 not in _TN_FIELD_18_VALUES or field_1c != _TN_FIELD_1C_VALUE:
        return None
    return f"Team Ninja chunk '{tag.decode('ascii')}'"


def _match_bzip2(head: bytes) -> str | None:
    level = head[3:4]
    is_bzip2 = (
        head.startswith(b"BZh")
        and level.isdigit()
        and level != b"0"
        and head[4:10] in _BZIP2_BLOCK_MAGICS
    )
    return _ARCHIVE if is_bzip2 else None


def _match_xdvdfs(prefix: bytes) -> str | None:
    magic = prefix[XDVDFS_OFFSET:_XDVDFS_END]
    return "XDVDFS disc image (XISO)" if magic == XDVDFS_MAGIC else None


_DETECTORS: Final[tuple[Callable[[bytes], str | None], ...]] = (
    _match_prefix,
    _match_adx,
    _match_team_ninja_chunk,
    _match_bzip2,
    _match_xdvdfs,
)


def match_signature(prefix: bytes) -> str | None:
    """Describe the game (or archive) signature present in a blob's prefix.

    `prefix` is the first bytes of the blob: at least `HEAD_BYTES` (or the whole blob if it
    is smaller) and up to past the XDVDFS magic to detect disc images.
    """
    for detect in _DETECTORS:
        if (description := detect(prefix)) is not None:
            return description
    return None


def _prefix_length(size: int) -> int:
    """Bytes to read from a blob of `size` bytes: just enough for all the signatures."""
    return _XDVDFS_END if size >= _XDVDFS_END else min(size, HEAD_BYTES)


def check_blob(
    path: str, size: int, read_prefix: Callable[[int], bytes], policy: Policy = DEFAULT_POLICY
) -> list[Violation]:
    """Apply the four rules to a blob and return its violations.

    `read_prefix(n)` returns the first `n` bytes of the blob (`n` never exceeds `size`).
    """
    violations: list[Violation] = []
    if (root := forbidden_root(path)) is not None:
        detail = f"path under '{root}/': {FORBIDDEN_ROOTS[root]}"
        violations.append(Violation(path, Rule.PATH, detail))
    if path not in policy.allowed and (ext := forbidden_extension(path)) is not None:
        detail = f"extension '{ext}': {FORBIDDEN_EXTENSIONS[ext]}"
        violations.append(Violation(path, Rule.EXTENSION, detail))
    if size > policy.max_bytes:
        detail = f"{size} bytes > limit {policy.max_bytes}"
        violations.append(Violation(path, Rule.SIZE, detail))
    if (signature := match_signature(read_prefix(_prefix_length(size)))) is not None:
        violations.append(Violation(path, Rule.SIGNATURE, f"{signature} signature"))
    return violations


def parse_allowlist(text: str) -> frozenset[str]:
    """Exact paths from `.hygiene-allow`: one per line; blank lines and `#...` are ignored."""
    lines = (line.strip() for line in text.splitlines())
    return frozenset(line for line in lines if line and not line.startswith("#"))


# --- Errors and git output parsing (pure) -------------------------------------------


class HygieneError(Exception):
    """The review could not complete (git or configuration); reported with exit code 2."""


class GitError(HygieneError):
    """git returned an error or unexpected output."""


@dataclass(frozen=True, slots=True)
class IndexEntry:
    """An entry of the git index (`git ls-files -s`)."""

    mode: str
    oid: str
    stage: int
    path: str


def _decode_path(raw: bytes) -> str:
    """Git path (bytes, UTF-8 by convention) to str, never failing.

    `surrogateescape` preserves non-UTF-8 bytes; `os.fsdecode` on Windows is strict.
    """
    return raw.decode("utf-8", "surrogateescape")


def parse_index_entries(output: bytes) -> list[IndexEntry]:
    """Parse `git ls-files -s -z`: `<mode> <oid> <stage>\\t<path>\\0` per entry."""
    entries: list[IndexEntry] = []
    for record in output.split(b"\0"):
        if not record:
            continue
        meta, _, path = record.partition(b"\t")
        mode, oid, stage = meta.decode("ascii").split(" ")
        entries.append(IndexEntry(mode, oid, int(stage), _decode_path(path)))
    return entries


def parse_name_list(output: bytes) -> list[str]:
    """Parse a NUL-separated list of paths (`-z`)."""
    return [_decode_path(raw) for raw in output.split(b"\0") if raw]


def parse_batch_check(output: bytes) -> dict[str, int]:
    """Parse `git cat-file --batch-check`: `<oid> <type> <size>` per line."""
    sizes: dict[str, int] = {}
    for line in output.decode("ascii").splitlines():
        fields = line.split(" ")
        if len(fields) != 3 or fields[1] != "blob":
            raise GitError(f"expected a blob in the index and git gave: {line!r}")
        oid, _, size = fields
        sizes[oid] = int(size)
    return sizes


# --- git IO: everything that touches the repo lives here ---------------------------------------

GITLINK_MODE: Final = "160000"
ALLOWLIST_PATH: Final = ".hygiene-allow"

# What is staged relative to HEAD (also on a branch with no commits yet). --no-renames: a
# rename shows up as A (new path) without git reading blobs to measure similarity.
# T (type change, e.g. symlink -> regular file) would slip through with only ACMR.
_STAGED_DIFF: Final = (
    "diff",
    "--cached",
    "--name-only",
    "-z",
    "--no-renames",
    "--no-color",
    "--diff-filter=AMT",
)


_BATCH_CHECK: Final = ("cat-file", "--batch-check=%(objectname) %(objecttype) %(objectsize)")
ALLOWLIST_MAX_BYTES: Final = 64 * 1024
GIT_TIMEOUT_SECONDS: Final = 60.0

# For every git call: a `refs/replace/*` cannot substitute the blob being judged, and in a
# partial clone a missing object is an error instead of a download that may hang.
_GIT_ENV: Final[Mapping[str, str]] = {"GIT_NO_REPLACE_OBJECTS": "1", "GIT_NO_LAZY_FETCH": "1"}


def _describe_failure(command: Sequence[str], returncode: int | None, stderr: bytes) -> str:
    message = stderr.decode("utf-8", "replace").strip() or "no error message"
    return f"`{shlex.join(command)}` failed (code {returncode}): {message}"


def _describe_timeout(command: Sequence[str], timeout: float) -> str:
    return f"`{shlex.join(command)}` did not finish in {timeout:g} s"


def _spawn(command: Sequence[str], cwd: Path, *, stdin: int) -> subprocess.Popen[bytes]:
    """Launch `command` with `_GIT_ENV`, pipes on stdout/stderr and its own group on POSIX."""
    try:
        return subprocess.Popen(
            command,
            cwd=cwd,
            env={**os.environ, **_GIT_ENV},
            stdin=stdin,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            process_group=None if sys.platform == "win32" else 0,
        )
    except OSError as error:
        raise GitError(f"could not run `{shlex.join(command)}` in {cwd}: {error}") from error


def _kill_tree(process: subprocess.Popen[bytes]) -> None:
    """Kill the process and its descendants, which would otherwise keep the pipes open.

    On Windows `cmd\\git.exe` is a launcher: the real git is its child and survives a plain
    `kill`. On POSIX the process leads its own group (`process_group=0`).
    """
    with contextlib.suppress(OSError, subprocess.SubprocessError):
        if sys.platform == "win32":
            system32 = Path(os.environ.get("SYSTEMROOT", r"C:\Windows"), "System32")
            command = [str(system32 / "taskkill.exe"), "/F", "/T", "/PID", str(process.pid)]
            subprocess.run(command, check=False, capture_output=True, timeout=10)
        else:
            os.killpg(process.pid, signal.SIGKILL)
    process.kill()


def run_command(
    command: Sequence[str], *, cwd: Path, stdin: bytes = b"", timeout: float = GIT_TIMEOUT_SECONDS
) -> subprocess.CompletedProcess[bytes]:
    """Run `command` with `_GIT_ENV`; failing to launch it or exceeding `timeout` is `GitError`."""
    with _spawn(command, cwd, stdin=subprocess.PIPE) as process:
        try:
            stdout, stderr = process.communicate(stdin, timeout=timeout)
        except subprocess.TimeoutExpired as error:
            _kill_tree(process)
            process.communicate()
            raise GitError(_describe_timeout(command, timeout)) from error
    return subprocess.CompletedProcess(command, process.returncode, stdout, stderr)


def read_command_prefix(
    command: Sequence[str], *, cwd: Path, length: int, timeout: float = GIT_TIMEOUT_SECONDS
) -> bytes:
    """First `length` bytes of `command`'s stdout, without reading the rest.

    The pipe is closed as soon as what is needed arrives: the process gets EPIPE and exits,
    so a multi-GB blob costs the same as a small one. A timer kills the process tree after
    `timeout`: it covers a blocked read, not just the final wait.
    """
    if length == 0:
        return b""
    expired = threading.Event()
    with _spawn(command, cwd, stdin=subprocess.DEVNULL) as process:
        assert process.stdout is not None and process.stderr is not None  # PIPE

        def expire() -> None:
            expired.set()
            _kill_tree(process)

        watchdog = threading.Timer(timeout, expire)
        watchdog.start()
        try:
            data = process.stdout.read(length)
            process.stdout.close()
            stderr = process.stderr.read()
            returncode = process.wait()
        finally:
            watchdog.cancel()
    if len(data) < length:
        if expired.is_set():
            raise GitError(_describe_timeout(command, timeout))
        raise GitError(_describe_failure(command, returncode, stderr))
    return data


def _run_git(args: Sequence[str], cwd: Path, stdin: bytes = b"") -> bytes:
    """Run git and return its stdout; a non-zero exit code is `GitError`."""
    command = ["git", *args]
    completed = run_command(command, cwd=cwd, stdin=stdin)
    if completed.returncode != 0:
        raise GitError(_describe_failure(command, completed.returncode, completed.stderr))
    return completed.stdout


class GitRepo:
    """Reads the index of a repo. git always runs from the tree root."""

    def __init__(self, toplevel: Path) -> None:
        self.toplevel = toplevel

    @classmethod
    def discover(cls, start: Path) -> GitRepo:
        """Repo that contains `start`, which can be any path inside the tree."""
        output = _run_git(["rev-parse", "--show-toplevel"], cwd=start)
        return cls(Path(_decode_path(output.rstrip(b"\r\n"))))

    def _git(self, *args: str, stdin: bytes = b"") -> bytes:
        return _run_git(args, cwd=self.toplevel, stdin=stdin)

    def index_entries(self) -> list[IndexEntry]:
        """All the index entries, with paths relative to the root."""
        return parse_index_entries(self._git("ls-files", "-s", "-z", "--full-name"))

    def staged_paths(self) -> list[str]:
        """Paths that the index adds, modifies or changes the type of relative to HEAD."""
        return parse_name_list(self._git(*_STAGED_DIFF))

    def blob_sizes(self, oids: Iterable[str]) -> dict[str, int]:
        """Size of each blob, in a single git call."""
        unique = dict.fromkeys(oids)
        if not unique:
            return {}
        request = "".join(f"{oid}\n" for oid in unique).encode("ascii")
        sizes = parse_batch_check(self._git(*_BATCH_CHECK, stdin=request))
        if missing := unique.keys() - sizes.keys():
            raise GitError(f"git gave no size for {len(missing)} blob(s): {sorted(missing)}")
        return sizes

    def resolve_blob(self, spec: str) -> str | None:
        """oid that `spec` points to (`HEAD:path`, `:0:path`); None if it does not exist.

        With `-q --verify`, git exits with 1 both when the path is missing and when HEAD does
        not exist yet.
        """
        command = ["git", "rev-parse", "-q", "--verify", spec]
        completed = run_command(command, cwd=self.toplevel)
        if completed.returncode == 1:
            return None
        if completed.returncode != 0:
            raise GitError(_describe_failure(command, completed.returncode, completed.stderr))
        return completed.stdout.decode("ascii").strip()

    def read_blob_prefix(self, oid: str, length: int) -> bytes:
        """First `length` bytes of the blob without dumping the rest (see `read_command_prefix`)."""
        command = ["git", "cat-file", "blob", oid]
        return read_command_prefix(command, cwd=self.toplevel, length=length)


@dataclass(frozen=True, slots=True)
class ScanReport:
    """Result of a review: blobs examined and violations found."""

    checked: int
    violations: tuple[Violation, ...]


def _load_allowlist(repo: GitRepo, spec: str) -> frozenset[str]:
    """Exceptions from `.hygiene-allow` at git version `spec` (never the one on disk)."""
    oid = repo.resolve_blob(spec)
    if oid is None:
        return frozenset()
    size = repo.blob_sizes([oid])[oid]
    if size > ALLOWLIST_MAX_BYTES:
        raise HygieneError(f"{ALLOWLIST_PATH} is {size} bytes; maximum is {ALLOWLIST_MAX_BYTES}")
    try:
        text = repo.read_blob_prefix(oid, size).decode("utf-8-sig")
    except UnicodeDecodeError as error:
        raise HygieneError(f"{ALLOWLIST_PATH} is not valid UTF-8: {error}") from error
    return parse_allowlist(text)


def scan(repo: GitRepo, *, staged: bool, max_bytes: int = DEFAULT_MAX_BYTES) -> ScanReport:
    """Check the index blobs: all of them or, with `staged`, only what is staged.

    The exception list comes from HEAD with `staged` (a commit does not exempt itself) and
    from the index in the full review (the PR's tree).
    """
    allowlist_spec = f"HEAD:{ALLOWLIST_PATH}" if staged else f":0:{ALLOWLIST_PATH}"
    policy = Policy(max_bytes=max_bytes, allowed=_load_allowlist(repo, allowlist_spec))
    entries = repo.index_entries()
    if staged:
        prepared = set(repo.staged_paths())
        entries = [e for e in entries if e.path in prepared]
    blobs = [e for e in entries if e.mode != GITLINK_MODE]
    sizes = repo.blob_sizes(e.oid for e in blobs)
    violations = tuple(
        violation
        for e in blobs
        for violation in check_blob(
            e.path, sizes[e.oid], partial(repo.read_blob_prefix, e.oid), policy
        )
    )
    return ScanReport(checked=len(blobs), violations=violations)


# --- CLI ----------------------------------------------------------------------------------


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="ngb-hygiene", description="Keeps game data from being versioned."
    )
    parser.add_argument(
        "--staged", action="store_true", help="check only what is staged (pre-commit hook)"
    )
    parser.add_argument(
        "--root", type=Path, default=Path(), help="any path inside the repo (default: .)"
    )
    parser.add_argument(
        "--max-bytes", type=int, default=DEFAULT_MAX_BYTES, help="maximum size per file"
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        repo = GitRepo.discover(args.root)
        report = scan(repo, staged=args.staged, max_bytes=args.max_bytes)
    except HygieneError as error:
        print(f"ngb-hygiene: {error}", file=sys.stderr)
        return 2
    for violation in report.violations:
        print(violation, file=sys.stderr)
    if report.violations:
        print(
            f"ngb-hygiene: {len(report.violations)} violation(s); nothing from the game goes "
            "into the repo. Remove it from the index with `git rm --cached -- <path>`.",
            file=sys.stderr,
        )
        return 1
    print(f"ngb-hygiene: {report.checked} file(s) checked, no game data.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
